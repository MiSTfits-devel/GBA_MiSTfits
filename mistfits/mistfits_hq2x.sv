 function automatic[7:0] channel_rule(input[7:0] e,input[7:0] a,input[7:0] b,input[7:0] d,input[5:0] k);
  reg[11:0] sum;begin case(k)
   1,11,12,13,17:sum=12*e+4*a;2,14,18:sum=12*e+4*d;3,15,19:sum=12*e+4*b;
   4,20,24,27:sum=8*e+4*d+4*b;5,21:sum=8*e+4*a+4*b;6,22:sum=8*e+4*a+4*d;
   25,29:sum=4*e+6*d+6*b;26:sum=14*e+d+b;28:sum=12*e+2*d+2*b;
   30:sum=10*e+4*b+2*d;31:sum=10*e+4*d+2*b;default:sum=16*e;endcase channel_rule=sum>>4;end
 endfunction
