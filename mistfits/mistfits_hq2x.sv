 function automatic different(input[23:0] x,input[23:0] y);
  reg signed[7:0] dr,dg,db;reg signed[8:0] t,u;reg signed[9:0] yy,v;
  begin dr=$signed({1'b0,x[23:17]})-$signed({1'b0,y[23:17]});dg=$signed({1'b0,x[15:9]})-$signed({1'b0,y[15:9]});db=$signed({1'b0,x[7:1]})-$signed({1'b0,y[7:1]});
   t=dr+db;yy=t+dg;u=dr-db;v=(dg<<<1)-t;different=!(yy>=-96&&yy<=95&&u>=-16&&u<=15&&v>=-24&&v<=23);end
 endfunction
